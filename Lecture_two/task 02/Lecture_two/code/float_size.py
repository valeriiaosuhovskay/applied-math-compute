"""Питання 1: як Python зберігає числа з плаваючою частиною і скільки байтів це займає."""
import struct
import sys
from decimal import Decimal

x = 1.5

# float у Python = число формату IEEE 754 binary64 ("double" у мові C).
# Саме значення займає 8 байтів = 64 біти: 1 біт знак + 11 біт порядок + 52 біти мантиса.
print("Розмір самого значення (struct, формат 'd'):", struct.calcsize("d"), "байтів")

# Але Python-об'єкт float має ще службові поля (лічильник посилань, вказівник на тип),
# тому sys.getsizeof повертає більше, ніж 8.
print("Розмір Python-об'єкта float:", sys.getsizeof(x), "байтів")
print("Для порівняння, розмір int 1:", sys.getsizeof(1), "байтів")

# Бітове представлення числа 1.5 (знак | порядок | мантиса)
bits = format(struct.unpack(">Q", struct.pack(">d", x))[0], "064b")
print("Біти 1.5:", bits[0], bits[1:12], bits[12:])

# Через двійкове представлення багато десяткових дробів зберігаються наближено:
print("0.1 + 0.2 =", 0.1 + 0.2)
print("Точне значення 0.1 у пам'яті:", Decimal(0.1))
